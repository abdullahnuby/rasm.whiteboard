import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const context = vm.createContext({});
vm.runInContext(await readFile('dist/timeline.js', 'utf8'), context);
assert.equal(vm.runInContext('RasmTimeline.sceneSeconds({duration: 3, speed: .5})', context), 6);
assert.equal(vm.runInContext('RasmTimeline.durationForSeconds(5.4, .5)', context), 2.7);
assert.equal(vm.runInContext('RasmTimeline.sceneSeconds({duration: 2.7, speed: .5})', context), 5.4);
assert.equal(vm.runInContext('RasmTimeline.clampSeconds(0)', context), 1);
assert.equal(vm.runInContext('RasmTimeline.clampSeconds(999)', context), 180);
assert.equal(vm.runInContext('RasmTimeline.formatTime(65.39)', context), '01:05.3');
const layout = vm.runInContext('RasmTimeline.layout([{duration:3,speed:.5},{duration:4,speed:1},{duration:2,speed:.25}], 40)', context);
assert.equal(layout.length, 3);
assert.equal(layout[0].start, 0);
assert.equal(layout[0].duration, 6);
assert.equal(layout[1].start, 6);
assert.equal(layout[2].start, 10);
assert.equal(layout[2].duration, 8);
assert.equal(vm.runInContext('RasmTimeline.totalSeconds([{duration:3,speed:.5},{duration:4,speed:1},{duration:2,speed:.25}])', context), 18);
console.log('RASM timeline tests passed.');
