import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const context = vm.createContext({ Math, Number, Promise, TypeError, Object });
vm.runInContext(await readFile('dist/reliability.js', 'utf8'), context);
const { fitDimensions, withinPixelBudget, createSerialQueue } = context.RasmReliability;
assert.deepEqual({ ...fitDimensions(1920, 1080) }, { width: 960, height: 540, pixels: 518400 });
assert.deepEqual({ ...fitDimensions(640, 480) }, { width: 640, height: 480, pixels: 307200 });
assert.equal(fitDimensions(0, 480), null);
assert.equal(withinPixelBudget(10, 20, 30), true);
assert.equal(withinPixelBudget(11, 20, 30), false);
assert.equal(withinPixelBudget(Number.MAX_SAFE_INTEGER, 1, Number.MAX_SAFE_INTEGER), false);
assert.equal(withinPixelBudget(-1, 1, 10), false);
const enqueue = createSerialQueue(), order = [];
const first = enqueue(async () => { await new Promise(resolve => setTimeout(resolve, 12)); order.push('first'); });
const second = enqueue(async () => { order.push('second'); });
await Promise.all([first, second]);
assert.deepEqual(order, ['first', 'second']);
await assert.rejects(enqueue(async () => { throw new Error('expected'); }), /expected/);
await enqueue(async () => { order.push('after-failure'); });
assert.deepEqual(order, ['first', 'second', 'after-failure']);
console.log('RASM reliability tests passed.');
